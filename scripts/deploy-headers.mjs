/* Post-build step: writes deploy/security-headers.caddy from security-headers.json (the same policy main.py
   applies), adding the SHA-256 of each inline script in dist/index.html to script-src. */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const policy = JSON.parse(readFileSync("security-headers.json", "utf8"));
const html = readFileSync("dist/index.html", "utf8");
const hashes = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(
  ([, body]) => `'sha256-${createHash("sha256").update(body, "utf8").digest("base64")}'`
);
const csp = { ...policy.csp, "script-src": [policy.csp["script-src"], ...hashes].join(" ") };
const cspValue = Object.entries(csp).map(([k, v]) => `${k} ${v}`).join("; ");
const lines = [
  "# GENERATED by scripts/deploy-headers.mjs on every build — edit security-headers.json instead.",
  "header {",
  `\tContent-Security-Policy "${cspValue}"`,
  ...Object.entries(policy.headers).map(([k, v]) => `\t${k} "${v}"`),
  "\t-Server",
  "}",
  "",
];
writeFileSync("deploy/security-headers.caddy", lines.join("\n"));
console.log(`deploy-headers: deploy/security-headers.caddy (${hashes.length} inline script hash${hashes.length === 1 ? "" : "es"})`);
